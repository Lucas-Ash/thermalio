def write_captions() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (text, label) in CAPTIONS.items():
        (OUT / f"{name}.caption.tex").write_text(
            f"\\caption{{{text}}}\n\\label{{fig:{label}}}\n",
            encoding="utf-8",
        )


def check_figures() -> None:
    missing = [path for path in FIGURES if not path.exists()]
    if missing:
        listing = "\n".join(f"  - {path.relative_to(ROOT)}" for path in missing)
        raise SystemExit(f"Missing Direction C report figures:\n{listing}")


def regenerate(quick: bool) -> None:
    app_cmd = [sys.executable, str(ROOT / "direction_c_applications.py")]
    sweep_cmd = [sys.executable, str(ROOT / "direction_c_studies.py")]
    if quick:
        app_cmd.append("--quick")
        sweep_cmd.append("--quick")
    subprocess.run(app_cmd, cwd=ROOT, check=True)
    subprocess.run(sweep_cmd, cwd=ROOT, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description="Check or regenerate Direction C report figures.")
    parser.add_argument("--regenerate", action="store_true", help="rerun Direction C plot-producing scripts")
    parser.add_argument("--quick", action="store_true", help="use quick mode when regenerating")
    args = parser.parse_args()

    if args.regenerate:
        regenerate(quick=args.quick)
    write_captions()
    check_figures()
    print(f"Direction C report figures available: {len(FIGURES)}")
    print(f"Caption snippets written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

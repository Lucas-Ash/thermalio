"""Check or regenerate Direction C report figures.

By default this script does not regenerate any plots. It verifies that the
existing Direction C images referenced by ``direction_C_nonfourier_report.tex``
are present and rewrites the LaTeX caption snippets under ``report_images/``.

Use ``--regenerate`` only when the underlying simulations should be rerun:

    MPLCONFIGDIR=/tmp/matplotlib python report_images/generate_direction_c_report_images.py --regenerate

For a smaller rerun of the application and sweep studies:

    MPLCONFIGDIR=/tmp/matplotlib python report_images/generate_direction_c_report_images.py --regenerate --quick
"""

